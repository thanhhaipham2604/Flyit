"""Question sets for the evaluation probes.

Every row is the same shape, so one runner can score all of them:

    (category, question, expect, contains, source_keywords, note)

    category         groups failures so they cluster in the report
    question         asked verbatim, typos included where that is the point
    expect           "answer", "refuse", or "either" for a human to judge
    contains         strings a correct answer should include; ANY match
                     counts, because the model phrases figures several ways.
                     None skips the correctness check.
    source_keywords  words a relevant citation title would contain, used by
                     the sweeps to measure citation precision. None skips it.
    note             why the row is here, for whoever reads a failure

BEHAVIOUR   does it answer what it should and refuse what it should
CORRECTNESS does the answer contain the right figure
REALISTIC   the same, asked the way people actually type
SWEEP       a smaller set with citation keywords, for parameter sweeps

REALISTIC exists because the first two were written like developer test
cases - clean, abstract, third person. Real users write "i bought a laptop
for $1800 for work lol can i claim it", and that difference hid an entire
class of failure: every question containing a dollar amount was refused.
"""

